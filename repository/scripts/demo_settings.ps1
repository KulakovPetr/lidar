# Единственное место, где меняют пути и параметры демонстрации.
# Сохраните файл и запустите run_demo.ps1. Отдельные команды $env:... не нужны.
# Если переменная уже задана в окне PowerShell, она важнее строки ниже.

# Папка записи rosbag2. Внутри должен лежать metadata.yaml, а не один выбранный файл .db3.
if (-not $env:BAG) {
  $env:BAG = 'c:\ds\12 lidar\reports\synthetic_audit\unpacked\cloud_with_fake_obj'
}

# Куда писать результат. Каждый запуск — новая пустая папка.
# Повторно ту же папку указать нельзя: скрипт откажется дописывать журнал.
if (-not $env:OUT) {
  $stamp = Get-Date -Format 'yyyyMMdd-HHmmss'
  $env:OUT = Join-Path 'c:\ds\12 lidar\reports\acceptance' ('demo-' + $stamp)
}

# Какой поток слушать.
# /lidar_points — запись, на которой снимали картинку в браузере.
# /sensing/lidar/hesai128/pointcloud — второй лидар, другой файл записи.
if (-not $env:TOPIC) { $env:TOPIC = '/lidar_points' }

# web — страница в браузере. На этой машине RViz не открывался.
if (-not $env:VIEW) { $env:VIEW = 'web' }

# Как часто обновлять картинку, кадров в секунду. Для просмотра и ролика оставьте 10.
if (-not $env:VIZ_HZ) { $env:VIZ_HZ = '10' }

# Скорость проигрывателя. 1.0 — как записано. Это не скорость расчёта.
if (-not $env:RATE) { $env:RATE = '1.0' }

# Очередь чтения. 2 — рабочее значение для этой записи. Больше не ставьте.
if (-not $env:READ_AHEAD) { $env:READ_AHEAD = '2' }

# Сколько процессов считают. Рабочее значение — 2.
if (-not $env:WORKERS) { $env:WORKERS = '2' }

# Номер сети ROS на этой машине. Второй детектор с тем же номером не запускайте.
if (-not $env:ROS_DOMAIN_ID) { $env:ROS_DOMAIN_ID = '120' }

# Сколько секунд по часам компьютера крутить запись.
# Пусто — весь файл, на этой машине около 8 минут.
# 45 — только начало: препятствие ещё далеко, всего сближения не будет.
